"""Dataset adapters. ``load_base_instance`` picks organizer data when present, else synthetic."""
from __future__ import annotations

from ..config import load_commodities, load_cost_model, load_settings
from ..schema import Instance
from . import organizer, synthetic
from .tables import AdapterError, build_instance


def load_base_instance(prefer: str = "auto") -> Instance:
    """prefer: 'auto' (organizer if present), 'organizer' or 'synthetic'."""
    if prefer == "organizer" or (prefer == "auto" and organizer.organizer_data_present()):
        return organizer.load()
    settings = load_settings()
    tables = synthetic.load_tables(seed=settings.get("random_seed", 42))
    inst = build_instance(tables, load_commodities(), load_cost_model(), settings, "SYNTHETIC")
    inst.notes.append("SYNTHETIC DATA: generated by freshroute.adapters.synthetic; not real-world data.")
    return inst


__all__ = ["AdapterError", "load_base_instance", "organizer", "synthetic"]
