import json

import pandas as pd
import streamlit as st

from common import ROOT, base_instance, badge, data_badges, page_setup, safe

page_setup("Data & Assumptions")


def body():
    from freshroute.config import cost_model_source
    from freshroute.schema import json_schema

    inst = base_instance()
    st.title("8 · Data & assumptions")
    st.markdown(data_badges(inst), unsafe_allow_html=True)
    if inst.source_label == "SYNTHETIC":
        st.warning("SYNTHETIC DATA. Hub and market locations are real places. Inventory, demand, prices, capacities and "
                   "lane parameters are generated by a seeded script (data/synthetic/). They are not real-world data. "
                   "Drop organizer files into data/organizer/ to replace them (see README).")
    for n in inst.notes:
        st.caption(n)

    tabs = st.tabs(["Inventory", "Lanes", "Markets", "Prices & demand", "Commodities", "Cost model", "Schema",
                    "Assumptions", "Limitations", "Baseline"])
    with tabs[0]:
        st.dataframe(pd.DataFrame([b.model_dump() for b in inst.batches]), hide_index=True, use_container_width=True)
    with tabs[1]:
        st.dataframe(pd.DataFrame([l.model_dump() for l in inst.lanes.values()]), hide_index=True, use_container_width=True)
        st.caption("Offline distances and times are synthetic approximations; live mode replaces them with OSRM routes.")
    with tabs[2]:
        st.dataframe(pd.DataFrame([d.model_dump() for d in inst.destinations.values()] +
                                  [h.model_dump() | {"kind": "hub"} for h in inst.hubs.values()]),
                     hide_index=True, use_container_width=True)
    with tabs[3]:
        pr = pd.DataFrame([{"dest_id": d, "commodity": c, "price_per_kg": v, "demand_kg": inst.demand.get((d, c), 0)}
                           for (d, c), v in inst.prices.items()])
        st.dataframe(pr, hide_index=True, use_container_width=True)
    with tabs[4]:
        st.dataframe(pd.DataFrame([c.model_dump() for c in inst.commodities.values()]), hide_index=True,
                     use_container_width=True)
        st.caption("PLACEHOLDER ASSUMPTIONS for calibration, not measured constants. rate(T) = Q10^((T−Tref)/10); "
                   "below the chilling threshold the rate is multiplied by the chill penalty.")
    with tabs[5]:
        src = cost_model_source()
        st.markdown(badge(f"source: {src.relative_to(ROOT)}", "neutral"), unsafe_allow_html=True)
        st.code(src.read_text(encoding="utf-8"), language="yaml")
        st.markdown("**Run settings**")
        st.code((ROOT / "config" / "settings.yaml").read_text(encoding="utf-8"), language="yaml")
    with tabs[6]:
        st.json(json_schema(), expanded=False)
    for tab, name in zip(tabs[7:], ["ASSUMPTIONS.md", "LIMITATIONS.md", "BASELINE.md"]):
        with tab:
            p = ROOT / "docs" / name
            st.markdown(p.read_text(encoding="utf-8") if p.exists() else f"docs/{name} not found.")


safe(body)
